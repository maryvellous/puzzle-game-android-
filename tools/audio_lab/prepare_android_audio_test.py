#!/usr/bin/env python3
"""Prepare 3 short SoundPool buffers for the separable Android audioTest build.

Input C4.1 WAVs are generated by the existing offline physics pipeline.
Normal app source assets and existing Bloop MP3s are never overwritten.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import wave
from pathlib import Path

import numpy as np

SAMPLE_RATE = 44100


def read_wav(path: Path) -> np.ndarray:
    with wave.open(str(path), "rb") as f:
        if (f.getframerate(), f.getnchannels(), f.getsampwidth()) != (SAMPLE_RATE,1,2):
            raise ValueError(f"Expected 44.1kHz PCM mono16, got {path}")
        s = np.frombuffer(f.readframes(f.getnframes()),dtype="<i2").astype(float)/32768
    if len(s) < SAMPLE_RATE//10 or not np.all(np.isfinite(s)):
        raise ValueError(f"Empty/invalid material: {path}")
    return s


def save(path: Path, x: np.ndarray):
    if not 0 < len(x) < SAMPLE_RATE*2 or np.max(np.abs(x)) >= .84:
        raise ValueError(f"Invalid generated buffer: {path}")
    path.parent.mkdir(parents=True,exist_ok=True)
    with wave.open(str(path), "wb") as f:
        f.setnchannels(1); f.setsampwidth(2); f.setframerate(SAMPLE_RATE)
        f.writeframes(np.rint(x*32767).clip(-32768,32767).astype("<i2").tobytes())


def impact_excerpt(x: np.ndarray)->np.ndarray:
    """Preserve the C4.1 +9% 40%-of-fusion timbre; trim only dead space."""
    amplitude=np.abs(x)
    threshold=max(0.0002,float(amplitude.max())*.006)
    active=np.flatnonzero(amplitude>threshold)
    if not active.size:raise ValueError("Missing audible collision")
    left=max(0,int(active[0]) - round(.006*SAMPLE_RATE))
    right=min(len(x),int(active[-1])+round(.025*SAMPLE_RATE))
    out=x[left:right].copy()
    fade=min(len(out)//6,int(.005*SAMPLE_RATE))
    out[:fade]*=np.linspace(0,1,fade)
    out[-fade:]*=np.linspace(1,0,fade)
    return out


def cyclic_excerpt(x: np.ndarray,seconds:float,amplification:float,
                   max_peak:float)->np.ndarray:
    """Find the audible C4.1 friction/compression body and create seamless loop.

    Sample extraction is a *buffer preparation* step; the live physics
    controls duration/intensity, unlike old fixed gameplay SFX.
    """
    target=int(seconds*SAMPLE_RATE)
    if len(x)<target:
        raise ValueError("Original recording shorter than selected loop")
    # Find a moving region without including the long silent scenario tail.
    window=max(1,int(.050*SAMPLE_RATE))
    energy=np.convolve(x*x,np.ones(window)/window,mode="valid")
    center=int(np.argmax(energy))+window//2
    start=max(0,min(len(x)-target,center-target//2))
    segment=x[start:start+target].copy()
    if np.sqrt(np.mean(segment*segment)) < .0001:
        raise ValueError("SFX material silent; no valid continuous texture")
    overlap=min(int(.040*SAMPLE_RATE),len(segment)//5)
    output=segment[:-overlap].copy()
    ramp=(np.arange(overlap)+.5)/overlap
    output[:overlap]=segment[-overlap:]*(1-ramp)+segment[:overlap]*ramp
    output-=np.mean(output)
    gain=min(amplification,max_peak/max(1e-9,np.max(np.abs(output))))
    output*=gain
    return output


def run(c41_dir:Path,out_dir:Path,report_dir:Path):
    sources={
        "impact":c41_dir/"02_impact_A_plus9_audible_40percent.wav",
        "impact_variant":c41_dir/"03_impact_B_plus16_audible_32percent.wav",
        "friction":c41_dir/"04_friction_adhesive_UNCHANGED.wav",
        "compression":c41_dir/"05_compression_B_UNCHANGED.wav",
    }
    x={key:read_wav(path) for key,path in sources.items()}
    sounds={
        "impact":impact_excerpt(x["impact"]),
        "impact_variant":impact_excerpt(x["impact_variant"]),
        "friction":cyclic_excerpt(x["friction"],.23,5.0,.08),
        "compression":cyclic_excerpt(x["compression"],.20,4.5,.065),
    }
    report={}
    for key,samples in sounds.items():
        output=out_dir/f"lava_test_{key}.wav"
        save(output,samples)
        with wave.open(str(output),"rb") as f:
            assert f.getframerate()==44100 and f.getnchannels()==1
            assert f.getsampwidth()==2 and f.getnframes()>2000
        report[key]={
            "src_c41":sources[key].name,
            "source_sha256":hashlib.sha256(sources[key].read_bytes()).hexdigest(),
            "generated_resource":str(output),
            "length_ms":round(len(samples)/SAMPLE_RATE*1000,1),
            "rms":round(float(np.sqrt(np.mean(samples*samples))),5),
            "peak":round(float(np.max(np.abs(samples))),5),
            "type":"one-shot" if key.startswith("impact") else "continuous loop, physics-gated",
        }
    report_dir.mkdir(parents=True,exist_ok=True)
    (report_dir/"android_audio_material.json").write_text(
        json.dumps({
            "status":"EXPERIMENTAL_ONLY",
            "source":"C4.1 physical audition WAVs",
            "mode":"precomputed acoustic material + realtime motion-controlled gain/rate via SoundPool",
            "full_modal_granular_realtime_engine":False,
            "materials":report,
        },ensure_ascii=False,indent=2),encoding="utf8")
    print(json.dumps(report,ensure_ascii=False,indent=2),flush=True)


if __name__=="__main__":
    parser=argparse.ArgumentParser()
    parser.add_argument("--c41",type=Path,default=Path("build/audio_lab/two_blob_c41"))
    parser.add_argument("--out",type=Path,default=Path("app/src/audioTest/res/raw"))
    parser.add_argument("--report",type=Path,default=Path("build/audio_test_assets"))
    a=parser.parse_args()
    run(a.c41,a.out,a.report)
